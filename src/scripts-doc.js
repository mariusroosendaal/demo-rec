// npm run scripts: writes NARRATION.md, every scenario's narration in one place, from the
// scenarios themselves (their `narration`, `narrator` and `voice`), so edit the scenarios, then run it.
// The introduction above the first script, and a "# Planned" part at the end (scripts with no
// scenario yet), are written by hand and kept.

import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { SCENARIO_DIR, WORKSPACE } from "./config.js";

// The narrator settings a variation stands for (src/narrate.js VARIANTS)
const variation = ({ stability = 0.5, style = 0 } = {}) =>
  stability === 0.4 && style === 0.25 ? "warm" : stability === 0.7 ? "steady" : "base";

const sections = [];
for (const file of fs.readdirSync(SCENARIO_DIR).filter((f) => f.endsWith(".js") && !f.startsWith("_")).sort()) {
  const scenario = (await import(pathToFileURL(path.join(SCENARIO_DIR, file)))).default;
  if (!scenario?.narration?.length) continue;
  const name = file.replace(/\.js$/, "");
  const { voice: pacer = "af_heart" } = scenario.narrator ?? {};
  // The voice of the video that's used, when it isn't the one the take is paced to
  const voice = scenario.voice ?? pacer;
  const paced = voice === pacer ? "" : ` · paced to ${pacer}`;
  const lines = scenario.narration.map(({ text, say, pause }, i) =>
    `${i + 1}. ${text}${say && say !== text ? ` _(spoken: “${say}”)_` : ""}${pause ? ` _(pause ${pause}s)_` : ""}`);
  sections.push(`## ${name}\n\n${voice}, ${variation(scenario.narrator)}${paced} · \`scenarios/${file}\` · \`output/${name}/narration/${voice.toLowerCase()}.mp4\`\n\n${lines.join("\n")}`);
}

const out = path.join(WORKSPACE, "NARRATION.md");
const old = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
const planned = old.includes("\n# Planned") ? old.slice(old.indexOf("\n# Planned")) : "";
// The introduction is the workspace's own once written: kept, up to the first script
const intro = old.includes("\n## ")
  ? old.slice(0, old.indexOf("\n## ") + 1)
  : `# Narration scripts

Every demo's spoken lines, which are also its subtitles. Generated by \`npm run scripts\` from
the scenarios: edit a scenario's \`narration\`, then run it again. Anything above the first
script is kept, and so is a "# Planned" part at the end.

`;
fs.writeFileSync(out, `${intro}${sections.join("\n\n")}
${planned}`);
console.log(`${path.relative(process.cwd(), out)}: ${sections.length} scripts`);
